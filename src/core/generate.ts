import type { Assertion, Locator, Recording, Settings, Step } from './types';

/** Quote a string as a single-quoted JS literal. */
export const q = (s: string) =>
  `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n').replace(/\r/g, '\\r')}'`;

export function locatorCode(l: Locator): string {
  switch (l.kind) {
    case 'testid':
      return `page.getByTestId(${q(l.value)})`;
    case 'role':
      return `page.getByRole(${q(l.role)}, { name: ${q(l.name)}, exact: true })`;
    case 'label':
      return `page.getByLabel(${q(l.value)}, { exact: true })`;
    case 'placeholder':
      return `page.getByPlaceholder(${q(l.value)}, { exact: true })`;
    case 'text':
      return `page.getByText(${q(l.value)}, { exact: true })`;
    case 'css':
      return `page.locator(${q(l.value)})`;
  }
}

/** Turn a full URL into a path when it is on the configured baseURL. */
export function toPath(url: string, baseURL: string): string {
  if (!baseURL) return url;
  try {
    const u = new URL(url);
    const b = new URL(baseURL);
    if (u.origin !== b.origin) return url;
    return u.pathname + u.search + u.hash;
  } catch {
    return url;
  }
}

function urlPattern(url: string, baseURL: string): string {
  const path = toPath(url, baseURL);
  if (path === url) return q(url);
  // Match the path at the end of the URL, ignoring origin.
  const escaped = path.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
  return `/${escaped}$/`;
}

function assertionCode(target: Locator | undefined, a: Assertion, baseURL: string): string {
  if (a.kind === 'url') return `await expect(page).toHaveURL(${urlPattern(a.value, baseURL)});`;
  if (!target) throw new Error(`Assertion "${a.kind}" needs a target element`);
  const loc = locatorCode(target);
  switch (a.kind) {
    case 'text':
      return `await expect(${loc}).toHaveText(${q(a.value)});`;
    case 'value':
      return `await expect(${loc}).toHaveValue(${q(a.value)});`;
    case 'visible':
      return `await expect(${loc}).toBeVisible();`;
    case 'hidden':
      return `await expect(${loc}).toBeHidden();`;
    case 'enabled':
      return `await expect(${loc}).toBeEnabled();`;
  }
}

function stepCode(step: Step, baseURL: string): string[] {
  switch (step.type) {
    case 'goto':
      return [`await page.goto(${q(toPath(step.url, baseURL))});`];
    case 'click':
      return withFragileNote(step.target, `await ${locatorCode(step.target)}.click();`);
    case 'fill': {
      const value = step.env ? `process.env.${step.env} ?? ''` : q(step.value);
      return withFragileNote(step.target, `await ${locatorCode(step.target)}.fill(${value});`);
    }
    case 'select':
      return withFragileNote(step.target, `await ${locatorCode(step.target)}.selectOption(${q(step.value)});`);
    case 'check':
      return withFragileNote(
        step.target,
        `await ${locatorCode(step.target)}.${step.checked ? 'check' : 'uncheck'}();`,
      );
    case 'press':
      return withFragileNote(step.target, `await ${locatorCode(step.target)}.press(${q(step.key)});`);
    case 'expect': {
      const code = assertionCode(step.target, step.assertion, baseURL);
      return step.target ? withFragileNote(step.target, code) : [code];
    }
  }
}

function withFragileNote(target: Locator, line: string): string[] {
  return target.kind === 'css' ? ['// TODO: fragile selector, add a data-testid to this element', line] : [line];
}

export function slugify(title: string): string {
  const slug = title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60)
    .replace(/-+$/, '');
  return slug || 'bug';
}

export interface Generated {
  code: string;
  fileName: string;
  envVars: string[];
}

/** Build a Playwright spec from a recording. Throws if the spec could not catch the bug. */
export function generateSpec(rec: Recording, settings: Pick<Settings, 'baseURL'>): Generated {
  if (!rec.steps.some((s) => s.type === 'expect')) {
    throw new Error('Add at least one "Expect" step, so the test fails on the bug.');
  }
  const title = rec.title.trim() || 'recorded bug';
  const steps = rec.steps[0]?.type === 'goto' ? rec.steps : [{ type: 'goto', url: rec.startUrl } as Step, ...rec.steps];
  const body = steps.flatMap((s) => stepCode(s, settings.baseURL)).map((l) => `  ${l}`);
  const envVars = [...new Set(rec.steps.flatMap((s) => (s.type === 'fill' && s.env ? [s.env] : [])))];

  const header = [
    `// Generated by Bug2Test. This test should FAIL until the bug is fixed.`,
    ...(rec.actual.trim() ? [`// Actual behaviour: ${rec.actual.trim().replace(/\n/g, ' ')}`] : []),
    ...(envVars.length ? [`// Needs env vars: ${envVars.join(', ')}`] : []),
    `import { test, expect } from '@playwright/test';`,
    ``,
  ];
  const code = [...header, `test(${q(`bug: ${title}`)}, async ({ page }) => {`, ...body, `});`, ``].join('\n');
  return { code, fileName: `${slugify(title)}.spec.ts`, envVars };
}

/** One-line, human description of a step (Markdown). */
export function describeStep(step: Step): string {
  const t = (l: Locator) => ('value' in l ? l.value : `${l.role} "${l.name}"`);
  switch (step.type) {
    case 'goto':
      return `Open ${step.url}`;
    case 'click':
      return `Click ${t(step.target)}`;
    case 'fill':
      return `Type ${step.env ? `$${step.env}` : `"${step.value}"`} into ${t(step.target)}`;
    case 'select':
      return `Select "${step.value}" in ${t(step.target)}`;
    case 'check':
      return `${step.checked ? 'Check' : 'Uncheck'} ${t(step.target)}`;
    case 'press':
      return `Press ${step.key} in ${t(step.target)}`;
    case 'expect': {
      const a = step.assertion;
      const what = step.target ? t(step.target) : 'page';
      if (a.kind === 'text' || a.kind === 'value') return `**Expected** ${what} to have ${a.kind} "${a.value}"`;
      if (a.kind === 'url') return `**Expected** URL to be ${a.value}`;
      return `**Expected** ${what} to be ${a.kind}`;
    }
  }
}

/** Markdown for the pull request body. */
export function prBody(rec: Recording, filePath: string): string {
  const lines = [
    `## Bug`,
    rec.title.trim() || 'Recorded bug',
    ``,
    `**Actual:** ${rec.actual.trim() || '_not given_'}`,
    ``,
    `## Steps`,
    ...rec.steps.map((s, i) => `${i + 1}. ${describeStep(s)}`),
    ``,
    `## Test`,
    `\`${filePath}\` fails on the current code. Fix the bug in this branch until it passes.`,
    ``,
    '```bash',
    `npx playwright test ${filePath}`,
    '```',
  ];
  if (rec.consoleErrors.length) {
    lines.push('', '## Console errors', '```', ...rec.consoleErrors.slice(0, 20), '```');
  }
  if (rec.networkFailures.length) {
    lines.push(
      '',
      '## Failed requests',
      '| Method | URL | Status |',
      '|---|---|---|',
      ...rec.networkFailures.slice(0, 20).map((n) => `| ${n.method} | ${n.url.replace(/\|/g, '\\|')} | ${n.status} |`),
    );
  }
  lines.push('', '---', '_Recorded with [Bug2Test](https://github.com/rahulcs754/bug2test)_');
  return lines.join('\n');
}
